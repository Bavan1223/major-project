@app.route("/api/status")
def api_status():

    events = read_events()

    file_events = events_by_source(
        events,
        "file_monitor"
    )

    network_events = events_by_source(
        events,
        "network_monitor"
    )

    process_events = events_by_source(
        events,
        "process_monitor"
    )

    detection_events = events_by_source(
        events,
        "detection_engine"
    )

    risk = calculate_risk(events)

    return jsonify({

        "status": "ONLINE",

        "monitoring": True,

        "safe_lab_mode": True,

        "protection_mode": "DRY_RUN",

        "event_count": len(events),

        "file_event_count":
            len(file_events),

        "network_event_count":
            len(network_events),

        "process_event_count":
            len(process_events),

        "detection_event_count":
            len(detection_events),

        "risk_level":
            risk["risk_level"],

        "risk_reason":
            risk["reason"],

        "timestamp":
            datetime.now().isoformat(
                timespec="seconds"
            )

    })


