@app.route("/api/network")
def api_network():

    events = read_events()

    network_events = build_network_summary(
        events
    )

    repeated_events = [
        event
        for event in events
        if (
            event.get("event_type")
            == "repeated_network_activity"
        )
    ]

    return jsonify({

        "count":
            len(network_events),

        "connections":
            network_events,

        "repeated_activity":
            latest_events(
                repeated_events,
                20
            )

    })


